// Regenerate public/js/calib.js from ../interpret/calibration.yaml (rerun after model / calibration changes).
const y = require('js-yaml'), fs = require('fs'), path = require('path');
const src = path.join(__dirname, '../../interpret/calibration.yaml');
const c = y.load(fs.readFileSync(src, 'utf8'));
const out = {
  source: c.source, n_images: c.n_images,
  quantiles: Object.fromEntries(Object.entries(c.quantiles).map(([k, v]) => [k, v.q])),
  type_bias: c.type_bias,
};
// reference-set size shown to users ("…와 비교한 순위") — from interpret/refset/summary.json when calibrated on it
const sumPath = path.join(__dirname, '../../interpret/refset/summary.json');
if (String(c.source).includes('refset/combined') && fs.existsSync(sumPath)) {
  const s = JSON.parse(fs.readFileSync(sumPath, 'utf8')).combined;
  if (s.n_images !== c.n_images) throw new Error(`summary.json n_images ${s.n_images} != calibration ${c.n_images}`);
  out.ref = { images: s.n_images, persons: s.persons, hands: s.hands, sources: 'PLSU + 11K Hands' };
}
fs.writeFileSync(path.join(__dirname, '../public/js/calib.js'),
  '// auto-generated by tools/gen_calib.cjs from interpret/calibration.yaml — do not hand-edit\n' +
  'export const CALIB = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('ok', Object.keys(out.quantiles).length, 'quantile keys');
