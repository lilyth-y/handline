"""Build interpret/calibration.yaml from a features jsonl:
  1) per-feature deciles for every pct('x.y') used in rules.yaml
  2) per-type additive biases so the 12 types come out roughly evenly (simple iterative balancing)
Rerun after a model change (e.g. v2):  python interpret/extract_batch.py --model weights/v2/best.pt && python interpret/calibrate.py
"""
import argparse, collections, json, re, sys
from pathlib import Path
import numpy as np, yaml
sys.path.insert(0, str(Path(__file__).resolve().parent))
import interpret as I

ap = argparse.ArgumentParser()
ap.add_argument("--features", default=str(I.HERE / "calib/val_features.jsonl"))
ap.add_argument("--iters", type=int, default=400)
ap.add_argument("--out", default=str(I.CALIB_PATH))
a = ap.parse_args()
rows = [json.loads(l) for l in open(a.features)]
rules = yaml.safe_load(I.RULES_PATH.read_text())
keys = sorted(set(re.findall(r"pct\('([^']+)'\)", I.RULES_PATH.read_text())))
quant = {}
for k in keys:
    obj, attr = k.split(".")
    vals = []
    for r in rows:
        src = r["relations"] if obj == "rel" else r["lines"][obj]
        v = src.get(attr)
        if v is not None and not isinstance(v, bool):
            vals.append(float(v))
    if vals:
        quant[k] = {"n": len(vals), "q": [round(float(x), 4) for x in np.percentile(vals, np.arange(0, 101, 10))]}
calib = {"source": a.features, "n_images": len(rows), "quantiles": quant, "type_bias": {t["id"]: 0.0 for t in rules["types"]}}

ids = [t["id"] for t in rules["types"]]
target = len(rows) / len(ids)
lucks_cache = [I.score_lucks(r, rules, calib) for r in rows]  # lucks do not depend on bias
best = None
for it in range(a.iters):
    cnt = collections.Counter(I.score_types(r, l, rules, calib)[0]["id"] for r, l in zip(rows, lucks_cache))
    spread = max(cnt.get(i, 0) for i in ids) - min(cnt.get(i, 0) for i in ids)
    if best is None or spread < best[0]:
        best = (spread, dict(calib["type_bias"]), cnt)
    step = 0.02 if it < 200 else 0.005
    for i in ids:
        c = cnt.get(i, 0)
        if c > target + 1: calib["type_bias"][i] -= step
        elif c < target - 1: calib["type_bias"][i] += step
calib["type_bias"] = {k: round(v, 3) for k, v in best[1].items()}
Path(a.out).write_text("# auto-generated by calibrate.py (do not hand-edit; rerun instead)\n" + yaml.safe_dump(calib, allow_unicode=True, sort_keys=False))
print("type counts:", dict(best[2]))
stars = collections.defaultdict(collections.Counter)
for l in lucks_cache:
    for k, v in l.items(): stars[k][v["stars"]] += 1
for k, c in stars.items(): print(k, sorted(c.items()))
